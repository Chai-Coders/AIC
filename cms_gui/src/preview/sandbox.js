// Turns the public website's source (frontend/) into a Sandpack project, so the
// AI Assistant page can render the whole site in the admin's browser with the
// draft applied. The site is a Vite app; Sandpack's in-browser bundler is not
// Vite, so a few Vite-only features are shimmed here:
//
// - `import.meta.env.VITE_*` is replaced with the values we pass in.
// - `import.meta.glob(...)` (only used for the optional build-time snapshot)
//   becomes an empty object.
// - Files in frontend/public (`/img/...`, `/css/...`, ...) are not copied into
//   the sandbox (they are ~250 MB); their absolute paths are pointed at the
//   running public site instead (`assetOrigin`).
// - @fontsource imports are swapped for the same packages loaded from a CDN.
//
// A small bridge script (bridge.js) is added to the sandbox. It serves draft
// content in place of the live API, and lets the CMS navigate the preview,
// outline an element for the walkthrough and pick an element by clicking.

import bridgeSource from './bridge.js?raw';

export const SANDBOX_ENTRY = '/src/main.jsx';
export const BRIDGE_PATH = '/src/__aic_preview/bridge.js';
export const CONTENT_PATH = '/src/__aic_preview/content.json';
export const HEAD_PATH = '/src/__aic_preview/head.js';
export const CHECK_PATH = '/src/__aic_preview/check.js';

// Folders under frontend/public that the site references by absolute path.
const PUBLIC_PREFIXES = ['img', 'pdfs', 'css', 'fonts', 'favicon.png', 'sitemap.xml'];
// Matches `/img/...` after a quote, `(`, or a space/comma (the second URL in a
// srcSet), so string literals, CSS url() and srcSet lists are all rewritten.
const PUBLIC_PATH_RE = new RegExp(
  `(^|["'\`(\\s,])/(${PUBLIC_PREFIXES.map((p) => p.replace('.', '\\.')).join('|')})(?=[/"'\`)?#\\s]|$)`,
  'gm',
);

const TEXT_EXTENSIONS = /\.(jsx?|tsx?|css|json|svg|html|md)$/i;

/**
 * Rewrites one source file for the sandbox. `path` is relative to frontend/
 * (e.g. "src/App.jsx"); `env` holds the VITE_* values.
 */
export function transformSource(path, code, { env = {}, assetOrigin = '' } = {}) {
  let out = code;

  out = out.replace(/import\.meta\.glob\s*\([^)]*\)/g, '({})');
  out = out.replace(/import\.meta\.env\.([A-Z_][A-Z0-9_]*)/g, (_, name) => {
    if (name === 'DEV') return 'false';
    if (name === 'PROD') return 'true';
    if (name === 'MODE') return '"production"';
    return name in env ? JSON.stringify(env[name]) : 'undefined';
  });
  out = out.replace(/import\.meta\.env\b/g, JSON.stringify(env));

  if (assetOrigin && /\.(jsx?|tsx?|css)$/i.test(path)) {
    out = out.replace(PUBLIC_PATH_RE, (_, before, rest) => `${before}${assetOrigin}/${rest}`);
  }

  if (`/${path}` === SANDBOX_ENTRY) {
    out = out.replace(/^\s*import\s+['"]@fontsource[^'"]*['"];?\s*$/gm, '');
    out = `import './__aic_preview/head.js';\nimport './__aic_preview/bridge.js';\nimport './__aic_preview/check.js';\n${out}`;
  }
  return out;
}

// The sandbox bundler ignores <head> in index.html, so stylesheets the site
// loads from there (and the @fontsource fonts main.jsx imports, whose CSS
// points at font files the bundler cannot serve) are added by head.js.
// Font Awesome comes from a CDN because fonts loaded cross-origin need CORS
// headers, which the site's host may not send; it is the same 4.7.0 release
// as frontend/public/css/font-awesome.min.css.
const STYLESHEETS = [
  'https://cdn.jsdelivr.net/npm/@fontsource-variable/manrope@5/index.css',
  'https://cdn.jsdelivr.net/npm/@fontsource-variable/source-serif-4@5/opsz.css',
  'https://cdn.jsdelivr.net/npm/@fontsource-variable/source-serif-4@5/opsz-italic.css',
  'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/4.7.0/css/font-awesome.min.css',
];

const HEAD_SOURCE = `// Generated by the CMS preview (sandbox.js).
for (const href of ${JSON.stringify(STYLESHEETS)}) {
  if (!document.querySelector('link[href="' + href + '"]')) {
    const link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = href;
    document.head.appendChild(link);
  }
}
`;

const INDEX_HTML = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  </head>
  <body>
    <div id="root"></div>
  </body>
</html>
`;

/**
 * Builds the Sandpack `files` map.
 *
 * - `sources`: { "src/App.jsx": "...", "package.json": "...", ... } relative to frontend/
 * - `codeEdits`: draft file contents with the same keys (null deletes a file)
 * - `content`: draft site content in the shape content:siteContent returns, or
 *   undefined to read the live API
 */
export function buildSandboxFiles({ sources, codeEdits = {}, content, env = {}, assetOrigin = '' }) {
  const merged = { ...sources };
  for (const [path, value] of Object.entries(codeEdits)) {
    if (value === null) delete merged[path];
    else merged[path] = value;
  }

  const files = {};
  for (const [path, code] of Object.entries(merged)) {
    if (!path.startsWith('src/') || !TEXT_EXTENSIONS.test(path)) continue;
    files[`/${path}`] = { code: transformSource(path, code, { env, assetOrigin }) };
  }

  // The bundler transpiles lazy routes only when they're opened, so a syntax error
  // in a page nobody has opened yet would go unnoticed. Importing every edited
  // file here makes the build check see them all.
  const edited = Object.entries(codeEdits)
    .filter(([path, value]) => value !== null && /^src\/.*\.jsx?$/.test(path) && `/${path}` !== SANDBOX_ENTRY)
    .map(([path]) => `import '/${path}';`);
  files[CHECK_PATH] = { code: `// Generated by the CMS preview (sandbox.js).\n${edited.join('\n')}\n`, hidden: true };

  files['/public/index.html'] = { code: INDEX_HTML, hidden: true };
  files[HEAD_PATH] = { code: HEAD_SOURCE, hidden: true };
  files[BRIDGE_PATH] = { code: bridgeSource, hidden: true };
  files[CONTENT_PATH] = { code: JSON.stringify(content ?? null), hidden: true };
  return files;
}

/** npm dependencies for the sandbox, from the site's package.json. */
export function sandboxDependencies(packageJsonText) {
  let pkg = {};
  try {
    pkg = JSON.parse(packageJsonText || '{}');
  } catch {
    // Fall through to the defaults below.
  }
  const deps = { ...(pkg.dependencies || {}) };
  for (const name of Object.keys(deps)) {
    if (name.startsWith('@fontsource')) delete deps[name];
  }
  return {
    react: '^19.0.0',
    'react-dom': '^19.0.0',
    'react-router-dom': '^7.0.0',
    ...deps,
  };
}
